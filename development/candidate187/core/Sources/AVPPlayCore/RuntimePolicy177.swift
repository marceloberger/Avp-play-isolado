import Foundation

/// Build177 policy. Historical pins/Jobs/receipts are readable, never migrated in place.
public enum RuntimePolicy177 {
    public static let label = "Klepton 850 cc2856c + TLS168"
    public static let revision = "850-cc2856c-tls168"
    public static let blocked = "Build177 exige Klepton 850 cc2856c + TLS168 íntegro. Operação bloqueada; nenhum fallback para 824 e nenhum Job antigo foi alterado."
    public static var sourceRoot: URL { DataLocation.base.appendingPathComponent("toolchains/850-cc2856c") }

    public static func source(at root: URL) throws -> Toolchain {
        do { let source = try Toolchain(root: root); try requireSource(source); return source }
        catch { throw RecipeError.invalid(blocked + " " + String(describing: error)) }
    }

    public static func requireSource(_ toolchain: Toolchain) throws {
        guard toolchain.version() == 850, toolchain.commit() == "cc2856c" else { throw RecipeError.invalid(blocked) }
        do {
            let hashes = try JSONDecoder().decode([String:String].self, from: Data(contentsOf: toolchain.root.appendingPathComponent(".isolated-source-sha256.json")))
            guard hashes == (try pinnedHashes()) else { throw RecipeError.invalid(blocked + " Recibo de origem não corresponde ao payload850 fixado.") }
            _ = try OptionalRuntime850.verifyFullIntegrity(of: toolchain)
            try OptionalRuntime850.verifySDK(at: toolchain.root)
            let (_, overlay) = try contract()
            for entry in overlay.files {
                guard try Hashing.sha256(of: toolchain.root.appendingPathComponent(entry.path)) == entry.originalSHA256,
                      let payload = Bundle.module.url(forResource: entry.resource, withExtension: nil),
                      try Hashing.sha256(of: payload) == entry.correctedSHA256 else { throw RecipeError.invalid(blocked) }
            }
        } catch { throw RecipeError.invalid(blocked + " " + String(describing: error)) }
    }

    static func pinnedHashes() throws -> [String:String] {
        guard let url = Bundle.module.url(forResource: "runtime177-source850", withExtension: "json") else { throw RecipeError.invalid(blocked) }
        return try JSONDecoder().decode([String:String].self, from: Data(contentsOf: url))
    }

    static func contract() throws -> (Data, ExperimentalTLS170.Overlay) {
        guard let url = Bundle.module.url(forResource: "tls170-overlay", withExtension: "json") else { throw RecipeError.invalid(blocked) }
        let data = try Data(contentsOf: url)
        let overlay = try JSONDecoder().decode(ExperimentalTLS170.Overlay.self, from: data)
        guard overlay.revision == revision, overlay.files.count == 4,
              Set(overlay.files.map(\.path)).count == 4,
              overlay.files.allSatisfy({ Recipe.isSafeRelativePath($0.path) && Recipe.isSafeName($0.resource) }) else { throw RecipeError.invalid(blocked) }
        return (data, overlay)
    }

    /// Check all pinned runtime files. The target table may be regenerated by Klepton's
    /// `run.sh`; after a build, accept only the byte-for-byte output of pinned targets.py
    /// for the prepared target and its unpacked APK inputs.
    public static func requireWorkspace(_ toolchain: Toolchain, generatedTarget: String? = nil, xcodeBuiltApp: URL? = nil) throws {
        guard toolchain.version() == 850, toolchain.commit() == "cc2856c" else { throw RecipeError.invalid(blocked) }
        let (data, overlay) = try contract()
        guard (try? Data(contentsOf: toolchain.root.appendingPathComponent(".experimental-tls170.json"))) == data else { throw RecipeError.invalid(blocked) }
        var hashes = try JSONDecoder().decode([String:String].self, from: Data(contentsOf: toolchain.root.appendingPathComponent(".isolated-source-sha256.json")))
        guard hashes.count == 2116, hashes == (try pinnedHashes()) else { throw RecipeError.invalid(blocked) }
        for file in overlay.files { hashes[file.path] = file.correctedSHA256 }
        let root = toolchain.root.resolvingSymlinksInPath().path + "/"
        for (path, hash) in hashes {
            let file = toolchain.root.appendingPathComponent(path)
            guard Recipe.isSafeRelativePath(path), file.resolvingSymlinksInPath().path.hasPrefix(root) else { throw RecipeError.invalid(blocked) }
            if path == "runtime/kl_target_table.h", generatedTarget != nil { continue }
            let actual = try Hashing.sha256(of: file)
            let adapted = path == "visionos/targets.py" && actual != hash
                ? try permittedRE4Hash(originalHash: hash) : nil
            let xcodeAdapted = path == "visionos/Info.plist" && actual != hash && xcodeBuiltApp != nil
                ? try permittedXcodeInfoPlist(in: toolchain, originalHash: hash, app: xcodeBuiltApp!) : false
            guard Recipe.isSafeRelativePath(path), file.resolvingSymlinksInPath().path.hasPrefix(root),
                  actual == hash || actual == adapted || xcodeAdapted else { throw RecipeError.invalid(blocked + " Arquivo: " + path) }
        }
        if let generatedTarget {
            try requireGeneratedTargetTable(toolchain, target: generatedTarget, root: root)
        }
        try OptionalRuntime850.verifySDK(at: toolchain.root)
    }

    static func generatedTargetTableData(in toolchain: Toolchain, target: String) throws -> Data {
        guard Recipe.isSafeName(target) else { throw RecipeError.invalid(blocked + " Target de tabela inválido.") }
        let targetDirectory = toolchain.root.appendingPathComponent(target, isDirectory: true)
        let stamp = targetDirectory.appendingPathComponent(".qi-prepared")
        let root = toolchain.root.resolvingSymlinksInPath().standardizedFileURL.path + "/"
        let script = toolchain.root.appendingPathComponent("visionos/targets.py")
        guard targetDirectory.resolvingSymlinksInPath().standardizedFileURL.path.hasPrefix(root),
              stamp.resolvingSymlinksInPath().standardizedFileURL.path.hasPrefix(root),
              FileManager.default.fileExists(atPath: stamp.path),
              FileManager.default.isExecutableFile(atPath: "/usr/bin/python3") else {
            throw RecipeError.invalid(blocked + " Não há evidência segura do target preparado para validar kl_target_table.h.")
        }

        // targets.py is executed only after every pinned input (including the script)
        // has passed its hash check above. -B and the restricted environment prevent
        // bytecode/cache writes or inherited target overrides.
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/python3")
        process.arguments = ["-B", script.path, "--c-table"]
        process.currentDirectoryURL = toolchain.root.appendingPathComponent("visionos", isDirectory: true)
        var environment = ["PATH": "/usr/bin:/bin:/usr/sbin:/sbin", "HOME": NSHomeDirectory(),
                           "USER": NSUserName(), "PYTHONDONTWRITEBYTECODE": "1", "PYTHONNOUSERSITE": "1"]
        if DraftRecipe.isGeneric(target) { environment["KLEPTON_GENERIC_TARGET"] = target }
        process.environment = environment
        let output = Pipe()
        process.standardOutput = output
        process.standardError = FileHandle.nullDevice
        process.standardInput = FileHandle.nullDevice
        do { try process.run() }
        catch { throw RecipeError.invalid(blocked + " Não foi possível executar targets.py fixado: \(error)") }
        let expected = output.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        guard process.terminationStatus == 0, !expected.isEmpty else {
            throw RecipeError.invalid(blocked + " targets.py não gerou uma tabela verificável para \(target).")
        }
        return expected
    }

    private static func requireGeneratedTargetTable(_ toolchain: Toolchain, target: String, root: String) throws {
        let table = toolchain.root.appendingPathComponent("runtime/kl_target_table.h")
        guard table.resolvingSymlinksInPath().standardizedFileURL.path.hasPrefix(root) else {
            throw RecipeError.invalid(blocked + " Arquivo gerado fora do workspace: runtime/kl_target_table.h.")
        }
        let expected = try generatedTargetTableData(in: toolchain, target: target)
        guard try Hashing.sha256(of: table) == Hashing.sha256(of: expected) else {
            throw RecipeError.invalid(blocked + " Arquivo gerado adulterado ou divergente: runtime/kl_target_table.h para \(target).")
        }
    }


    static func permittedXcodeInfoPlist(in toolchain: Toolchain,
                                                originalHash: String,
                                                app: URL) throws -> Bool {
        let root = toolchain.root.resolvingSymlinksInPath().path + "/"
        guard app.resolvingSymlinksInPath().path.hasPrefix(root) else { return false }
        let originalURL = sourceRoot.appendingPathComponent("visionos/Info.plist")
        guard try Hashing.sha256(of: originalURL) == originalHash else { return false }

        let keys = [
            "NSAccessoryTrackingUsageDescription",
            "NSBluetoothAlwaysUsageDescription",
            "NSHandsTrackingUsageDescription",
            "NSLocalNetworkUsageDescription",
            "NSMicrophoneUsageDescription",
            "NSWorldSensingUsageDescription"
        ]

        func plist(_ url: URL) throws -> [String: Any] {
            let data = try Data(contentsOf: url)
            guard let dictionary = try PropertyListSerialization.propertyList(
                from: data, options: [], format: nil
            ) as? [String: Any] else {
                throw RecipeError.invalid(blocked + " Info.plist inválido.")
            }
            return dictionary
        }

        let original = try plist(originalURL)
        let workspace = try plist(toolchain.root.appendingPathComponent("visionos/Info.plist"))
        let compiled = try plist(app.appendingPathComponent("Info.plist"))

        var expected = original
        for key in keys {
            guard let value = original[key] as? String,
                  !value.isEmpty,
                  workspace[key] == nil,
                  compiled[key] as? String == value else { return false }
            expected.removeValue(forKey: key)
        }

        guard NSDictionary(dictionary: workspace).isEqual(to: expected) else {
            return false
        }

        let project = toolchain.root.appendingPathComponent("visionos")
            .appendingPathComponent(app.deletingPathExtension().lastPathComponent + ".xcodeproj/project.pbxproj")
        guard project.resolvingSymlinksInPath().path.hasPrefix(root),
              FileManager.default.fileExists(atPath: project.path) else { return false }

        let data = try Data(contentsOf: project)
        guard let objects = try PropertyListSerialization.propertyList(
            from: data, options: [], format: nil
        ) as? [String: Any],
              let entries = objects["objects"] as? [String: Any] else { return false }

        // Project-level configurations legitimately inherit target settings. Follow only
        // this product's native target configuration list, never unrelated targets.
        let targets = entries.values.compactMap { $0 as? [String: Any] }.filter {
            $0["isa"] as? String == "PBXNativeTarget" && $0["name"] as? String == app.deletingPathExtension().lastPathComponent
        }
        guard targets.count == 1,
              let listID = targets[0]["buildConfigurationList"] as? String,
              let list = entries[listID] as? [String: Any],
              let ids = list["buildConfigurations"] as? [String], !ids.isEmpty else { return false }
        let configurations = ids.compactMap { entries[$0] as? [String: Any] }
            .filter { $0["isa"] as? String == "XCBuildConfiguration" }
            .compactMap { $0["buildSettings"] as? [String: Any] }
        guard configurations.count == ids.count else { return false }

        guard !configurations.isEmpty else { return false }

        for key in keys {
            let setting = "INFOPLIST_KEY_" + key
            guard configurations.allSatisfy({
                $0[setting] as? String == original[key] as? String
            }) else { return false }
        }
        return true
    }

    private static func permittedRE4Hash(originalHash: String) throws -> String {
        let original = sourceRoot.appendingPathComponent("visionos/targets.py")
        guard try Hashing.sha256(of: original) == originalHash else { throw RecipeError.invalid(blocked) }
        let scratch = DataLocation.temporaryDirectory.appendingPathComponent("runtime177-re4-\(UUID())")
        defer { try? FileManager.default.removeItem(at: scratch) }
        try FileManager.default.createDirectory(at: scratch.appendingPathComponent("visionos"), withIntermediateDirectories: true)
        try FileManager.default.copyItem(at: original, to: scratch.appendingPathComponent("visionos/targets.py"))
        return try Hashing.sha256(of: KleptonRecipeCompatibility.addResidentEvilTargetMetadata(to: scratch))
    }

    public static func requireArtifact(_ artifact: ReusableBuild, target: String? = nil) throws {
        _ = try source(at: sourceRoot)
        let resolvedTarget = try target ?? preparedTarget(in: artifact.workspace)
        try requireWorkspace(Toolchain(root: artifact.workspace), generatedTarget: resolvedTarget, xcodeBuiltApp: artifact.app)
        let info = try ReusableBuild.infoPlist(artifact.app.appendingPathComponent("Info.plist"))
        guard let version = info["CFBundleVersion"] as? String,
              let stamp = AppStamp.parse(version), stamp.toolchain == 850, stamp.modified else {
            throw RecipeError.invalid(blocked + " Artefato não comprova 850 + TLS168.")
        }
        try artifact.verifyCopy(artifact.app)
    }

    private static func preparedTarget(in workspace: URL) throws -> String {
        let prepared = try FileManager.default.contentsOfDirectory(at: workspace, includingPropertiesForKeys: [.isDirectoryKey])
            .filter { Recipe.isSafeName($0.lastPathComponent)
                && FileManager.default.fileExists(atPath: $0.appendingPathComponent(".qi-prepared").path) }
        guard prepared.count == 1, let target = prepared.first?.lastPathComponent else {
            throw RecipeError.invalid(blocked + " O workspace não tem um único target preparado verificável.")
        }
        return target
    }

    public static func evidence() throws -> [String:String] {
        let (data, _) = try contract()
        return ["Runtime.toolchain": "850-cc2856c", "Runtime.overlay": revision,
                "Runtime.overlaySHA256": Hashing.sha256(of: data)]
    }
}
